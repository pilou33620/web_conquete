def _profil(code):
    from . import rules as R
    return R.FACTIONS.get(code, {}).get('profil') or PROFIL_SO.get(code)


def _si(profil=None, cote=False):
    """Condition d'un événement aléatoire : partie de toute la France (géographie 3), pays du bon profil ou au bord
    de la mer."""
    def ok(g, code):
        if g.geo.version < 3:
            return False
        return (not profil or _profil(code) == profil) and (not cote or code in COTE)
    return ok


